// Default chromium command-line flags for the kiosk. Exposed via /api/kiosk-flags
// so the Advanced settings modal can show/edit them, and chromium-autostart.sh
// reads them from the same endpoint so flag changes propagate without editing
// any shell script.
//   --use-gl / --ignore-gpu-blocklist / --enable-zero-copy / CanvasOopRasterization
//   were removed because they conflict with the Pi chromium wrapper's
//   --use-angle=gles and triggered GPU re-init loops that broke nested
//   overflow:auto scrolling.
//   --window-size is appended dynamically from the saved resolution, not stored
//   here.
// Defaults assume labwc as the compositor (see chromium-autostart.sh), where
// chromium gets a real V3D GL context — so the GPU-accel flags actually take
// effect instead of being dead weight like they were under cage.
// --disable-renderer-accessibility stops chromium auto-enabling the a11y tree
// when it detects the system at-spi bus (heavy CPU on dynamic pages).
const DEFAULT_KIOSK_FLAGS = [
  '--ozone-platform=wayland',
  '--enable-features=UseOzonePlatform,VaapiVideoDecoder',
  '--ignore-gpu-blocklist',
  '--enable-gpu-rasterization',
  '--disable-renderer-accessibility',
  '--kiosk',
  '--start-fullscreen',
  '--noerrdialogs',
  '--disable-infobars',
  '--disable-popup-blocking',
  '--no-sandbox',
  '--remote-debugging-port=9222',
].join('\n');

// Clicker / presentation-remote keystrokes that can break the kiosk and should
// be eaten by the compositor (labwc) BEFORE chromium ever sees them. A web page
// cannot reliably preventDefault these. Observed on the deployed device with
// the actual MK118 remote (the original spec table was guesswork):
//   long-press Tab   -> Alt+Tab  (labwc window-cycle)
//   long-press Enter  -> Alt+F4   (kills chromium window)
//   long-press ArrowUp -> F5      (full page refresh — disruptive in a kiosk)
// labwc keybind syntax (verified against labwc-config.5 / labwc-actions.5 and
// the labwc source): modifier prefixes are S-/C-/A-/W- (A- = Alt); bare keys
// like "F5" are valid.
//
// KEY MECHANISM — read before editing, this is subtle and the first two
// attempts were wrong:
//   labwc forwards a key to the focused app ONLY if it matches NO keybind.
//   If it matches a keybind, labwc ABSORBS it (app never sees it) and runs
//   that bind's action.
//   - `<action name="None"/>` as the sole action means "clear an earlier
//     binding". For A-Tab / A-F4 (which ARE labwc defaults) that REMOVES the
//     default bind → the key then matches nothing → forwarded to Chromium →
//     Alt+F4 still closes Chromium. So `None` is exactly wrong here.
//   - An empty <keybind> is ambiguous across labwc versions.
//   - Correct: bind to a REAL but inert action so the bind MATCHES and the key
//     is absorbed. `Raise` restacks the focused window; with one fullscreen
//     kiosk window it does nothing visible, but it still counts as a match so
//     the key never reaches Chromium. That neutralises both labwc's own
//     default (Alt+Tab/Alt+F4) and non-default keys (F5, which labwc otherwise
//     wouldn't grab at all and would forward to Chromium = page refresh).
//
// Observed on the deployed device with the real MK118 remote (the original
// spec table was guesswork): long-press Tab=Alt+Tab, long-press Enter=Alt+F4,
// long-press ArrowUp=F5.
const NOOP_ACTION = '<action name="Raise"/>';
const SUPPRESSIBLE_KEYS = {
  'alt+f4': { keybind: 'A-F4', label: 'Alt+F4 (long-press Enter — kills Chromium)' },
  'alt+tab': { keybind: 'A-Tab', label: 'Alt+Tab (long-press Tab — switches windows)' },
  'f5': { keybind: 'F5', label: 'F5 (long-press ArrowUp — full page refresh)' },
};
const DEFAULT_SUPPRESS_KEYS = ['alt+f4', 'alt+tab', 'f5'];

// Emit a complete rc.xml (not a fragment) — labwc reads exactly one rc.xml
// from $XDG_CONFIG_HOME/labwc/ and does not merge.
function buildLabwcConfig(suppressKeys) {
  const binds = (Array.isArray(suppressKeys) ? suppressKeys : [])
    .map((k) => SUPPRESSIBLE_KEYS[k])
    .filter(Boolean)
    .map((k) => `    <keybind key="${k.keybind}">${NOOP_ACTION}</keybind>`)
    .join('\n');
  return `<?xml version="1.0"?>
<!-- Generated by OrbitControl /api/labwc-config — do not edit by hand. -->
<labwc_config>
  <keyboard>
${binds || '    <!-- no keys suppressed -->'}
  </keyboard>
</labwc_config>
`;
}

function readSettings() {
  let s = {};
  try {
    s = JSON.parse(fs.readFileSync(SETTINGS_PATH, 'utf8'));
  } catch {}
  return {
    url: s.url || 'https://example.com',
    resolution: s.resolution || { width: 1920, height: 1080 },
    hideCursorDelay: s.hideCursorDelay != null ? s.hideCursorDelay : 10,
    name: s.name || 'Orbit',
    zoom: s.zoom != null ? s.zoom : 1,
    kioskFlags: s.kioskFlags != null ? s.kioskFlags : DEFAULT_KIOSK_FLAGS,
    remoteDebugEnabled: s.remoteDebugEnabled === true,
    suppressKeys: Array.isArray(s.suppressKeys)
      ? s.suppressKeys.filter((k) => SUPPRESSIBLE_KEYS[k])
      : DEFAULT_SUPPRESS_KEYS,
    bookmarks: Array.isArray(s.bookmarks) ? s.bookmarks : [],
  };
}

function writeSettings(settings) {
  fs.writeFileSync(SETTINGS_PATH, JSON.stringify(settings, null, 2));
}

async function toggleAdminPanel() {
  const settings = readSettings();
  const port = parseInt(process.env.PORT, 10) || 80;
  const adminUrl = 'http://localhost' + (port === 80 ? '' : ':' + port) + '/';
  let currentUrl = '';
  try {
    currentUrl = (await cdp.getCurrentUrl()) || '';
  } catch {}
  const isOnAdmin = /^https?:\/\/(localhost|127\.0\.0\.1|0\.0\.0\.0)(:|\/|$)/.test(currentUrl);
  const target = isOnAdmin ? (settings.url || 'https://example.com') : adminUrl;
  await cdp.navigate(target);
  return { target, was: currentUrl };
}

