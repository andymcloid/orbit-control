let updateInProgress = false;

app.post('/api/update', async (req, res) => {
  if (updateInProgress) return res.status(409).json({ error: 'update already running' });
  if (process.env.ORBIT_DEV === '1') {
    return res.status(400).json({ error: 'update is disabled in dev mode' });
  }
  updateInProgress = true;
  res.json({ ok: true });

  const broadcast = (msg) => {
    const data = JSON.stringify(msg);
    for (const ws of controlClients) {
      if (ws.readyState === 1) ws.send(data);
    }
  };

  try {
    await update.runUpdate(__dirname, {
      onLine: (stream, line) => broadcast({ type: 'update-output', stream, line }),
      onStep: (step) => broadcast({ type: 'update-step', step }),
    });
    update.invalidateGitInfoCache();
    broadcast({ type: 'update-status', status: 'restarting' });
    // Restart via systemd rather than process.exit(0). Under load (10 hotkey
    // fs.createReadStreams blocking the libuv thread pool + high-fps preview
    // broadcasts) Node's own exit has been observed to stall mid-V8-shutdown,
    // leaving the service "active" but stuck. `systemctl restart` is an
    // out-of-band SIGTERM from PID 1 — kernel terminates blocked threads
    // and systemd guarantees the new instance comes up.
    setTimeout(() => {
      spawn('systemctl', ['restart', 'orbit-control'], {
        detached: true,
        stdio: 'ignore',
      }).unref();
    }, 1000);
  } catch (err) {
    broadcast({ type: 'update-status', status: 'error', error: err.message });
    updateInProgress = false;
  }
});

// --- WebSocket (control panel live updates + preview) ---

const controlClients = new Set();

function broadcastStatus() {
  const data = JSON.stringify({
    type: 'status',
    browser_connected: cdp.isConnected(),
    settings: readSettings(),
  });
  for (const ws of controlClients) {
    if (ws.readyState === 1) ws.send(data);
  }
}

function updatePreview() {
  // Preview FPS is a per-client preference (stored in the client's localStorage)
  // because it's about *how fast the operator wants to watch* the kiosk, not
  // anything about the kiosk itself. With multiple panels open we use the
  // max requested rate so a slow client doesn't throttle a fast one — the
  // slow one just receives more frames than it strictly needs.
  let maxFps = 1;
  let wsWant = false;
  for (const ws of controlClients) {
    if (!ws._wantPreview) continue;
    wsWant = true;
    const fps = ws._previewFps || 1;
    if (fps > maxFps) maxFps = fps;
  }
  const anyWant = wsWant || mjpegClients.size > 0;
  if (anyWant && cdp.isConnected()) {
    cdp.setPreviewFps(maxFps);
    cdp.startPreview();
  } else {
    cdp.stopPreview();
  }
}

wss.on('connection', (ws) => {
  controlClients.add(ws);
  ws._wantPreview = false;
  ws._previewFps = 1;

  ws.send(JSON.stringify({
    type: 'status',
    browser_connected: cdp.isConnected(),
    settings: readSettings(),
  }));
  // Fire a system-info/wifi push to this WS immediately so it doesn't have to
  // wait up to STATUS_PUSH_INTERVAL_MS for the next periodic broadcast.
  pushStatusUpdates();

  ws.on('message', (raw) => {
    let msg;
    try { msg = JSON.parse(raw); } catch { return; }

    if (msg.type === 'preview-start') {
      ws._wantPreview = true;
      if (msg.fps) ws._previewFps = Math.max(1, Math.min(30, parseInt(msg.fps, 10) || 1));
      updatePreview();
    } else if (msg.type === 'preview-stop') {
      ws._wantPreview = false;
      updatePreview();
    } else if (msg.type === 'preview-fps') {
      ws._previewFps = Math.max(1, Math.min(30, parseInt(msg.fps, 10) || 1));
      updatePreview();
    } else if (msg.type === 'mouse') {
      // Forward raw pointer events from the preview pane to chromium via CDP.
      // Coords arrive as normalized 0..1 (the preview video can be at any
      // resolution); scale here by the kiosk's actual viewport size so CDP
      // gets coordinates in the page's CSS pixel space. Wheel deltas pass
      // through as-is since they're already in CSS pixels.
      const { action } = msg;
      if (typeof msg.x !== 'number' || typeof msg.y !== 'number') return;
      const res = readSettings().resolution || { width: 1920, height: 1080 };
      const x = Math.max(0, Math.min(res.width,  msg.x * res.width));
      const y = Math.max(0, Math.min(res.height, msg.y * res.height));
      cdp.mouseEvent(action, x, y, {
        button: msg.button,
        buttons: msg.buttons,
        dx: msg.dx,
        dy: msg.dy,
        clickCount: msg.clickCount,
      }).catch(() => {});
    }
  });

  ws.on('close', () => {
    controlClients.delete(ws);
    updatePreview();
  });
});

// --- MJPEG preview stream over HTTP ---
// Each connected admin panel opens a long-lived `GET /preview.mjpeg` request.
// chromium's screencast JPEGs are written to all open responses as multipart
// frames (the same protocol IP cameras use). The browser handles decode +
// repaint natively via <img>, so there's zero JS per frame and no encoding
// step on the Pi — just byte-pipe from chromium → HTTP clients.
const MJPEG_BOUNDARY = 'orbit-frame';
const mjpegClients = new Set();

cdp.setOnScreenshotFrame((jpegBuf) => {
  if (mjpegClients.size === 0) return;
  const header = Buffer.from(
    `\r\n--${MJPEG_BOUNDARY}\r\nContent-Type: image/jpeg\r\nContent-Length: ${jpegBuf.length}\r\n\r\n`,
    'ascii'
  );
  for (const res of mjpegClients) {
    try {
      res.write(header);
      res.write(jpegBuf);
    } catch {}
  }
});

app.get('/preview.mjpeg', (req, res) => {
  res.writeHead(200, {
    'Content-Type': `multipart/x-mixed-replace; boundary=${MJPEG_BOUNDARY}`,
    'Cache-Control': 'no-cache, no-store, max-age=0',
    'Pragma': 'no-cache',
    'Connection': 'close',
    'X-Accel-Buffering': 'no', // disable proxy buffering (cloudflared, nginx)
  });
  mjpegClients.add(res);
  // Trigger screencast if not already running so frames start flowing
  // immediately, without waiting for the panel's WS preview-start.
  updatePreview();
  req.on('close', () => {
    mjpegClients.delete(res);
    updatePreview();
  });
  req.on('error', () => {
    mjpegClients.delete(res);
    updatePreview();
  });
});

// --- CDP connection state ---
cdp.setOnConnectChange(async (connected) => {
  broadcastStatus();
  if (connected) {
    updatePreview();
    const settings = readSettings();
    if (settings.zoom && settings.zoom !== 1) {
      cdp.setZoom(settings.zoom).catch(() => {});
    }
    // Navigate to saved URL if browser is on a blank page
    try {
      const currentUrl = await cdp.getCurrentUrl();
      if (settings.url && (!currentUrl || currentUrl === 'about:blank' || currentUrl === 'chrome://newtab/')) {
        cdp.navigate(settings.url).catch(() => {});
      }
    } catch {}
  }
});

// --- Start ---

const PORT = parseInt(process.env.PORT, 10) || 80;
// Push system-info + wifi-status to all connected control clients every few
// seconds. Replaces the previous per-client HTTP polling — same data, one
// gather, broadcast over the existing WS so there's no duplicate work and
// no roundtrip storm.
const STATUS_PUSH_INTERVAL_MS = 5000;
function broadcastJson(obj) {
  const data = JSON.stringify(obj);
  for (const ws of controlClients) {
    if (ws.readyState === 1) {
      try { ws.send(data); } catch {}
    }
  }
}

async function pushStatusUpdates() {
  if (controlClients.size === 0) return;
  try {
    const info = await getSystemInfo();
    info.git = update.getGitInfo(__dirname);
    broadcastJson({ type: 'system-info', info });
  } catch {}
  try {
    const [status, saved] = await Promise.all([wifi.getStatus(), wifi.listSaved()]);
    broadcastJson({ type: 'wifi-status', status, saved });
  } catch {}
}
setInterval(pushStatusUpdates, STATUS_PUSH_INTERVAL_MS);

server.listen(PORT, () => {
  console.log(`OrbitControl running on http://0.0.0.0:${PORT}`);
  cdp.connect();
  hotkey.start(() => {
    toggleAdminPanel().catch((err) =>
      console.warn('[hotkey] toggle failed:', err.message)
    );
  });
});
